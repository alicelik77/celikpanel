// alpha.130 (Boston, 8 Nov 2026): "Postfix is not running" while Postfix ran.
// On Debian and Ubuntu postfix.service is a oneshot wrapper that stays
// "active (exited)"; the live overlay put that text on the scan's
// "active (running)" and the problems rule read it as stopped.

func liveReadings(t *testing.T, now time.Time, units ...transport.ServiceHealthUnit) {
	t.Helper()
	serviceHealth = serviceHealthState{}
	t.Cleanup(func() { serviceHealth = serviceHealthState{} })
	serviceHealth.record(now, units, nil, 1)
}

func TestServiceHealthUnitReadsPostfixInstanceOnlyOnApt(t *testing.T) {
	cases := []struct{ id, family, unit, want string }{
		{"postfix", "apt", "postfix", "postfix@-"},
		{"postfix", "pacman", "postfix", "postfix"},
		{"postfix", "dnf", "postfix", "postfix"},
		{"nginx", "apt", "nginx", "nginx"},
		{"wireguard", "apt", "wg-quick@wg0", "wg-quick@wg0"},
		{"postgresql", "apt", "postgresql@17-main", "postgresql@17-main"},
		{"php-fpm", "apt", "php8.3-fpm", "php8.3-fpm"},
	}
	for _, c := range cases {
		if got := serviceHealthUnit(c.id, c.family, c.unit); got != c.want {
			t.Errorf("%s/%s/%s = %q, want %q", c.id, c.family, c.unit, got, c.want)
		}
		if !serviceUnitNameOK(serviceHealthUnit(c.id, c.family, c.unit)) {
			t.Errorf("%s: the health unit would be refused by the Agent", c.id)
		}
	}
}

func TestOverlayDoesNotCallAnUpWrapperOrOneshotStopped(t *testing.T) {
	now := time.Date(2026, 11, 8, 6, 0, 0, 0, time.UTC)
	liveReadings(t, now,
		// Ubuntu/Debian Postfix: the wrapper is exited, the instance runs.
		transport.ServiceHealthUnit{Unit: "postfix@-", ActiveState: "active", SubState: "running"},
		transport.ServiceHealthUnit{Unit: "postfix", ActiveState: "active", SubState: "exited"},
		// WireGuard's wg-quick is a oneshot: exited is up.
		transport.ServiceHealthUnit{Unit: "wg-quick@wg0", ActiveState: "active", SubState: "exited"},
		// An init-script unit generated by systemd (postfwd on Debian).
		transport.ServiceHealthUnit{Unit: "postfwd", ActiveState: "active", SubState: "exited"},
		// PostgreSQL's apt wrapper never proves a cluster.
		transport.ServiceHealthUnit{Unit: "postgresql", ActiveState: "active", SubState: "exited"},
		transport.ServiceHealthUnit{Unit: "nginx", ActiveState: "failed", SubState: "failed"},
	)
	observations := []serviceObservation{
		{ID: "postfix", IsInstalled: true, Status: "active (running)", Unit: "postfix"},
		{ID: "wireguard", IsInstalled: true, Status: "active (running)", Unit: "wg-quick@wg0"},
		{ID: "postfwd", IsInstalled: true, Status: "active (running)", Unit: "postfwd"},
		{ID: "postgresql", IsInstalled: true, Status: "inactive (dead)", Unit: "postgresql"},
		{ID: "nginx", IsInstalled: true, Status: "active (running)", Unit: "nginx"},
	}
	live, liveAt := overlayLiveServiceStatus(observations, "apt", now.Add(time.Minute))
	want := map[string]string{
		"postfix": "active (running)", "wireguard": "active (running)", "postfwd": "active (running)",
		"postgresql": "active (exited)", "nginx": "failed (failed)",
	}
	for _, o := range live {
		if o.Status != want[o.ID] {
			t.Errorf("%s status %q, want %q", o.ID, o.Status, want[o.ID])
		}
		if !liveAt[o.ID].Equal(now) {
			t.Errorf("%s observed at %v", o.ID, liveAt[o.ID])
		}
	}
	problems, unknown := serviceProblems(live, core.ManagedServiceHostProfile{PackageFamily: "apt"}, now.Add(-24*time.Hour), liveAt, now.Add(time.Minute))
	if unknown != nil {
		t.Fatalf("every service had a live reading: %+v", unknown)
	}
	stopped := map[string]string{}
	for _, p := range problems {
		stopped[p.Subject] = p.ObservedAt
	}
	if _, ok := stopped["postfix"]; ok {
		t.Fatal("a running Postfix behind its wrapper was called stopped")
	}
	if _, ok := stopped["wireguard"]; ok {
		t.Fatal("an up oneshot was called stopped")
	}
	if stopped["nginx"] != metricsTime(now) {
		t.Fatalf("a failed nginx must be a problem seen at the reading's time: %+v", problems)
	}
	if _, ok := stopped["postgresql"]; !ok {
		t.Fatal("PostgreSQL with only its wrapper active is not running")
	}
	// The start action stays on the catalogue unit the Agent acts on.
	for _, p := range problems {
		if p.Subject == "nginx" && p.Unit != "nginx" {
			t.Fatalf("start unit %q", p.Unit)
		}
	}
}

func TestDeadPostfixInstanceBehindActiveWrapperIsStopped(t *testing.T) {
	now := time.Date(2026, 11, 8, 6, 0, 0, 0, time.UTC)
	liveReadings(t, now,
		transport.ServiceHealthUnit{Unit: "postfix@-", ActiveState: "failed", SubState: "failed"},
	)
	live, liveAt := overlayLiveServiceStatus([]serviceObservation{{ID: "postfix", IsInstalled: true, Status: "active (running)", Unit: "postfix"}}, "apt", now)
	problems, _ := serviceProblems(live, core.ManagedServiceHostProfile{PackageFamily: "apt"}, now, liveAt, now)
	if len(problems) != 1 || problems[0].Unit != "postfix" || problems[0].Action.Kind != "start_service" {
		t.Fatalf("problems %+v", problems)
	}
	// On Arch postfix.service is the daemon: its own reading decides.
	liveReadings(t, now, transport.ServiceHealthUnit{Unit: "postfix", ActiveState: "active", SubState: "running"})
	live, liveAt = overlayLiveServiceStatus([]serviceObservation{{ID: "postfix", IsInstalled: true, Status: "inactive (dead)", Unit: "postfix"}}, "pacman", now)
	if problems, _ := serviceProblems(live, core.ManagedServiceHostProfile{PackageFamily: "pacman"}, now, liveAt, now); len(problems) != 0 {
		t.Fatalf("arch problems %+v", problems)
	}
}

func TestAnOldScanAloneIsNotACurrentProblem(t *testing.T) {
	now := time.Date(2026, 11, 8, 6, 0, 0, 0, time.UTC)
	serviceHealth = serviceHealthState{}
	t.Cleanup(func() { serviceHealth = serviceHealthState{} })
	observations := []serviceObservation{{ID: "nginx", IsInstalled: true, Status: "inactive (dead)", Unit: "nginx"}}
	host := core.ManagedServiceHostProfile{PackageFamily: "apt"}
	// A scan of a day ago and no live reading: not checked, not a problem.
	live, liveAt := overlayLiveServiceStatus(observations, "apt", now)
	problems, unknown := serviceProblems(live, host, now.Add(-24*time.Hour), liveAt, now)
	if len(problems) != 0 || unknown == nil || unknown.Source != "services" || unknown.Reason != "stale" {
		t.Fatalf("stale scan: %+v %+v", problems, unknown)
	}
	// A scan of five minutes ago still says it, with its own time.
	scanned := now.Add(-5 * time.Minute)
	problems, unknown = serviceProblems(live, host, scanned, liveAt, now)
	if unknown != nil || len(problems) != 1 || problems[0].ObservedAt != metricsTime(scanned) {
		t.Fatalf("recent scan: %+v %+v", problems, unknown)
	}
	// A scan dated in the future proves nothing.
	if _, unknown = serviceProblems(live, host, now.Add(time.Hour), liveAt, now); unknown == nil {
		t.Fatal("a future scan was trusted")
	}
}

func TestServiceHealthReportSaysRunningByTheScanRule(t *testing.T) {
	now := time.Date(2026, 11, 8, 6, 0, 0, 0, time.UTC)
	reading := func(unit, active, sub string) transport.ServiceHealthUnit {
		return transport.ServiceHealthUnit{Unit: unit, ActiveState: active, SubState: sub}
	}
	if !serviceHealthReady("wireguard", "apt", "wg-quick@wg0", reading("wg-quick@wg0", "active", "exited")) {
		t.Fatal("oneshot exited is up")
	}
	if serviceHealthReady("postgresql", "apt", "postgresql", reading("postgresql", "active", "exited")) {
		t.Fatal("the PostgreSQL wrapper proves nothing")
	}
	if !serviceHealthReady("postgresql", "pacman", "postgresql", reading("postgresql", "active", "running")) {
		t.Fatal("Arch PostgreSQL is its own daemon")
	}
	if serviceHealthReady("nginx", "apt", "nginx", reading("nginx", "activating", "start")) {
		t.Fatal("activating is not yet up")
	}
	_ = now
}
