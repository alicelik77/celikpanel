// S4 R2b: a site's scheduled tasks as timers in its slice (site_tasks.go,
// site_tasks_move.go, side_doors_cron.go), with the fix round's tests.

// taskTestHost is a fake systemd and cron for the tasks tests. Its cron
// behaves as measured (Stage 1 F1) and as Debian's cron 3.0pl1 reads: the
// crontab lives in a spool file under three header lines, `crontab -l`
// prints it without them, and `crontab -u <account>` is refused for an
// account /etc/cron.allow leaves out (or /etc/cron.deny names, without a
// cron.allow) - a crontab the account already has stays.
type taskTestHost struct {
	mu      sync.Mutex
	unitDir string
	calls   []string
	enabled map[string]bool
	active  map[string]bool
	removes int
	// onCrontabRead runs before each `crontab -l` (racing changes).
	onCrontabRead func(account string)
	// site runs before each systemctl call: the site's own code, looping
	// (it may try to install a crontab with `crontab -`).
	site func()
	// installFails makes `crontab -` fail.
	installFails bool
	// ended records the uids whose crontab processes were ended.
	ended []int
}

const (
	taskTestAccount = "shop_example_test"
	taskTestSite    = 7
)

func taskTestHome() string { return hostingpath.SubscriptionsRoot() + "/2/sites/9" }

func taskTestTarget() siteTaskTarget {
	return siteTaskTarget{SiteID: taskTestSite, Domain: "shop.example.test", Account: taskTestAccount, Group: taskTestAccount, UID: 1500, GID: 1500, Home: taskTestHome()}
}

// cronHeader is what Debian's crontab writes above an installed crontab.
const cronHeader = "# DO NOT EDIT THIS FILE - edit the master and reinstall.\n# (- installed on Sat Nov 22 10:00:00 2026)\n# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n"

func spoolPath(account string) string { return filepath.Join(siteCronSpoolDirs[0], account) }

// refused: cron's access files keep the account out, as crontab decides.
func (h *taskTestHost) refused(account string) bool {
	if raw, err := os.ReadFile(cronAllowPath); err == nil {
		for _, name := range nameLines(string(raw)) {
			if name == account {
				return false
			}
		}
		return true
	}
	if raw, err := os.ReadFile(cronDenyPath); err == nil {
		for _, name := range nameLines(string(raw)) {
			if name == account {
				return true
			}
		}
	}
	return false
}

// crontab is the account's crontab as `crontab -l` would print it (ok:
// there is one), read by root from the spool.
func (h *taskTestHost) crontab(account string) (string, bool) {
	raw, err := os.ReadFile(spoolPath(account))
	if err != nil {
		return "", false
	}
	return crontabListView(string(raw)), true
}

// install is `crontab -u <account> -` (header included), as crontab does it.
func (h *taskTestHost) install(account, content string) error {
	if h.refused(account) {
		return errors.New("crontab: The user " + account + " cannot use this program (crontab)")
	}
	if h.installFails {
		return errors.New("crontab: write error: No space left on device")
	}
	return os.WriteFile(spoolPath(account), []byte(cronHeader+content), 0o600)
}

