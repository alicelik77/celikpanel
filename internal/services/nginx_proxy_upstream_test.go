func renderProxyVhost(t *testing.T, target string, resolution *HostResolution) string {
	t.Helper()
	ng, err := NewNginxGenerator()
	if err != nil {
		t.Fatal(err)
	}
	if resolution != nil {
		ng.SetHostResolution(*resolution)
	}
	out, err := ng.Render(VhostData{
		SiteID: 3, Domain: "proxy.example", DocumentRoot: "/var/www/proxy.example",
		ACMEChallengeRoot: testACMEChallengeRoot, ProjectType: "proxy", ForwardTo: target, SSLType: "none",
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// A target that needs no DNS keeps the plain form, byte for byte what
// earlier releases wrote; a host name is looked up per request through the
// server's own resolver, so an unresolvable name can never make nginx refuse
// its configuration.
func TestProxyTargetForm(t *testing.T) {
	resolved := &HostResolution{
		Nameservers: []string{"127.0.0.53", "[2001:db8::53]"},
		HostsNames:  map[string]bool{"app.internal": true},
	}
	for _, tc := range []struct {
		name, target string
		plain        bool
		rewrite      string
	}{
		{"IPv4 address", "http://127.0.0.1:8080", true, ""},
		{"IPv6 address", "http://[::1]:8080/app/", true, ""},
		{"localhost", "https://localhost:8443/base", true, ""},
		{"a name in /etc/hosts", "http://app.internal:3000", true, ""},
		{"host name", "http://backend.example:8080", false, ""},
		{"host name, root path", "http://backend.example:8080/", false, ""},
		{"host name, path with slash", "https://backend.example/base/", false, "        rewrite (?s)^/(.*)$ /base/$1 break;\n"},
		{"host name, path without slash", "https://backend.example/base", false, "        rewrite (?s)^/(.*)$ /base$1 break;\n"},
		{"host name, query", "http://backend.example/app/?tenant=a%20b", false, "        rewrite (?s)^/(.*)$ /app/$1?tenant=a%20b break;\n"},
		{"host name, path decoding to nginx syntax", "http://backend.example/a%24b/", true, ""},
		{"host name, path decoding to a space", "http://backend.example/a%20b/", true, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			out := renderProxyVhost(t, tc.target, resolved)
			if tc.plain {
				if !strings.Contains(out, "        proxy_pass "+tc.target+";\n        proxy_http_version 1.1;\n") ||
					strings.Contains(out, "resolver ") || strings.Contains(out, "$celikpanel_upstream") {
					t.Fatalf("plain form expected:\n%s", out)
				}
				return
			}
			origin := tc.target[:strings.Index(tc.target, "://")+3]
			rest := tc.target[len(origin):]
			if slash := strings.IndexByte(rest, '/'); slash >= 0 {
				rest = rest[:slash]
			}
			want := "        resolver 127.0.0.53 [2001:db8::53];\n" +
				"        set $celikpanel_upstream " + origin + rest + ";\n" +
				tc.rewrite +
				"        proxy_pass $celikpanel_upstream;\n        proxy_http_version 1.1;\n"
			if !strings.Contains(out, want) {
				t.Fatalf("run-time lookup form expected:\n%s\nin:\n%s", want, out)
			}
			if strings.Contains(out, "proxy_pass "+tc.target) {
				t.Fatal("the start-time form is still written")
			}
		})
	}
}

// With no readable /etc/resolv.conf (tests read none: the hermetic seam),
// the resolver is glibc's own default, 127.0.0.1.
func TestProxyTargetResolverDefault(t *testing.T) {
	out := renderProxyVhost(t, "http://backend.example:8080", nil)
	if !strings.Contains(out, "        resolver 127.0.0.1;\n") {
		t.Fatalf("resolver default:\n%s", out)
	}
}

// The run-time form sits in both server blocks of an HTTPS proxy site and
// after the www redirect's return (rewrite-module directives run in order).
func TestProxyTargetFormWithHTTPSAndWWW(t *testing.T) {
	ng, err := NewNginxGenerator()
	if err != nil {
		t.Fatal(err)
	}
	ng.SetHostResolution(HostResolution{Nameservers: []string{"192.0.2.53"}})
	out, err := ng.Render(VhostData{
		SiteID: 3, Domain: "proxy.example", DocumentRoot: "/var/www/proxy.example",
		ACMEChallengeRoot: testACMEChallengeRoot, ProjectType: "proxy", ForwardTo: "http://backend.example/base/",
		SSLType: "custom", SSLCert: "/etc/ssl/a.pem", SSLKey: "/etc/ssl/a.key", RedirectWWW: true,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Count(out, "proxy_pass $celikpanel_upstream;"); got != 2 {
		t.Fatalf("%d proxy_pass lines, want 2:\n%s", got, out)
	}
	redirect, rewrite := strings.Index(out, "return 301 $scheme://www.proxy.example$request_uri;"), strings.Index(out, "rewrite (?s)")
	if redirect < 0 || rewrite < 0 || redirect > rewrite {
		t.Fatalf("the www redirect must come before the rewrite:\n%s", out)
	}
}
