func TestParseResolvConfNameservers(t *testing.T) {
	text := "# Generated by systemd-resolved\nnameserver 127.0.0.53\noptions edns0 trust-ad\nsearch example\n" +
		"nameserver fe80::1%eth0\nnameserver 2001:db8::53\n  nameserver   192.0.2.1  \nnameserver not-an-ip\nnameserver 192.0.2.2\n"
	got := parseResolvConfNameservers(text)
	want := []string{"127.0.0.53", "[2001:db8::53]", "192.0.2.1"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %q, want %q (at most three, zone-scoped and invalid left out)", got, want)
	}
	if got := parseResolvConfNameservers("search example\n"); got != nil {
		t.Fatalf("no nameserver lines: %q", got)
	}
}

