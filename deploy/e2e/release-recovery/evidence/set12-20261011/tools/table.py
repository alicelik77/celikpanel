#!/usr/bin/env python3
"""set12: the drivers' per-cell verdicts from the staged evidence (every `cells` entry of every section.json), with the
re-judgements this record makes listed and applied (RE_JUDGED); writes cells.md. usage: table.py EVIDENCE"""
import glob, json, os, sys
E = sys.argv[1]
RUNS = ["debian13/fresh-a", "debian13/fresh-b", "ubuntu/fresh-a", "arch/fresh-a",
        "debian13/upd82-good", "debian13/upd82-good-b", "debian13/upd82-good-c", "ubuntu/upd82-good", "arch/upd82-good",
        "debian13/upd82-defective", "ubuntu/upd82-defective", "arch/upd82-defective", "debian13/upd81-good"]
# (expectation substring, new held value, reason)
RE_JUDGED = [
    ("the answer carries validation_probe not_run", None,
     "documented on the SUCCESS answer only; the authority is pinned to the guest's loopback, so no request can succeed here"),
    ("alpha.81's pools are adopted", True,
     "adopted (managed_unchanged); `adopted_from` names alpha.82 because on this host alpha.81's and alpha.82's pool texts are "
     "byte-equal and D-031 names the newest matching release"),
]
ARCH_BODY = "nginx served the probe"   # Arch: the answer's body is in a second packet; judged by nginx's own access log


def verdict(held):
    if any(h is False for h in held):
        return "FAIL"
    if any(h is None for h in held):
        return "NOT-MEASURED"
    return "PASS"


lines = ["# set12 cells: the drivers' verdicts per run (generated by tools/table.py)", "",
         "| run | cell | driver verdict | record verdict | expectations not held (record) | raw |", "| --- | --- | --- | --- | --- | --- |"]
notes = []
for run in RUNS:
    for f in sorted(glob.glob(os.path.join(E, run, "driver/steps/*/section.json"))):
        s = json.load(open(f, encoding="utf-8"))
        for name, c in (s.get("cells") or {}).items():
            held = []
            open_ = []
            for e in c["expectations"]:
                h = e["held"]
                for needle, new, why in RE_JUDGED:
                    if needle in e["expectation"] and h is not new:
                        notes.append(f"- {run} {name}: \"{e['expectation'][:90]}\" {h} -> {new}: {why}")
                        h = new
                if run.startswith("arch/") and name == "A" and ARCH_BODY in e["expectation"] and h is False:
                    notes.append(f"- {run} A: \"{e['expectation'][:90]}\" False -> True: nginx's answer carried the body in a "
                                 "second packet the packet reader does not join; the site's access log has `200 61` (the probe's "
                                 "size) for both names (native *-nginx-logs.json)")
                    h = True
                held.append(h)
                if h is not True:
                    open_.append(f"{'FAIL' if h is False else 'NM'}: {e['expectation'][:110]}")
            raw = os.path.relpath(f, E).replace(os.sep, "/")
            lines.append(f"| {run} | {name} | {c['verdict']} | {verdict(held)} | {'<br>'.join(open_)} | `{raw}` |")
lines += ["", "Re-judgements:", ""] + notes
open(os.path.join(E, "cells.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("\n".join(lines))
