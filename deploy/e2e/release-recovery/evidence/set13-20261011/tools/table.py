#!/usr/bin/env python3
"""set13: the drivers' per-cell verdicts from the staged evidence (every `cells` entry of every section.json) and the
record's verdicts where they differ (RECORD), with the reason; also every section whose driver verdict was not passed
and that holds no judged cell (a harness error before the judgement). Writes cells.md. usage: table.py EVIDENCE"""
import glob
import json
import os
import sys

E = sys.argv[1]
RUNS = ["debian13/fresh-a", "debian13/fresh-b", "ubuntu/fresh-a", "ubuntu/fresh-b"]
# (run, cell) -> (record verdict, reason)
RECORD = {
    ("debian13/fresh-a", "C4"): ("NOT-MEASURED", "precondition not met (harness order): C3 ran before C4 and its refused vhost takes left the "
                                 "vhost's ledger row `foreign / nginx_refused`; the Domains row shows that row, not the unread pool "
                                 "(the page, the ledger row `unknown / not_read:timeout` and the journal held); measured in debian13/fresh-b"),
    ("ubuntu/fresh-a", "C4"): ("NOT-MEASURED", "precondition not met (harness): no answered read between C2's refused take (pool row "
                               "`owner_edited / reload_failed`) and the hold, after the lab had put CelikPanel's text back; an unread "
                               "observation does not replace an edited row (documented); measured in ubuntu/fresh-b"),
}
SECTION_NOTES = {
    ("debian13/fresh-a", "C5-app-unit"): ("NOT-MEASURED (sub-cells b-d read from the raw files; e not reached)",
                                          "harness error in (e): the harness's own systemd-analyze run while the program was hidden "
                                          "(PermissionError) before the take; recovery removed the shims and the bind; measured in "
                                          "debian13/fresh-b"),
}


def verdict(held):
    if any(h is False for h in held):
        return "FAIL"
    if any(h is None for h in held):
        return "NOT-MEASURED"
    return "PASS"


lines = ["# set13 cells: the drivers' verdicts per run (generated by tools/table.py)", "",
         "| run | cell | driver verdict | record verdict | expectations not held | raw |", "| --- | --- | --- | --- | --- | --- |"]
notes = []
for run in RUNS:
    for f in sorted(glob.glob(os.path.join(E, run, "driver/steps/*/section.json"))):
        s = json.load(open(f, encoding="utf-8"))
        raw = os.path.relpath(f, E).replace(os.sep, "/")
        cells = s.get("cells") or {}
        key = s.get("section")
        if not cells and (run, key) in SECTION_NOTES:
            rec, why = SECTION_NOTES[(run, key)]
            lines.append(f"| {run} | {key} | {s.get('verdict')} | {rec} | (no judgement: {s.get('error', '')[:80]}...) | `{raw}` |")
            notes.append(f"- {run} {key}: {why}")
            continue
        for name, c in cells.items():
            held = [e["held"] for e in c["expectations"]]
            open_ = [f"{'FAIL' if e['held'] is False else 'NM'}: {e['expectation'][:110]}" for e in c["expectations"] if e["held"] is not True]
            rec = verdict(held)
            if (run, name) in RECORD:
                rec, why = RECORD[(run, name)]
                notes.append(f"- {run} {name}: driver {c['verdict']} -> {rec}: {why}")
            lines.append(f"| {run} | {name} | {c['verdict']} | {rec} | {'<br>'.join(open_)} | `{raw}` |")
lines += ["", "Record verdicts that differ from the driver's:", ""] + notes
open(os.path.join(E, "cells.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("\n".join(lines))
